"""
Programmatic tex table bodies.

Generates \\input-able tabular bodies into results/tex_tables/ from the
pipeline CSVs.  Captions/labels stay in the main tex; these files contain
ONLY the tabular environment, so every printed number is pipeline-generated.

Tables:
  tab_interaction_body.tex   interaction regressions (HC1 SEs, R2)
  tab_kramers_body.tex       Kramers escape observables (dual estimator,
                             bootstrap CIs, post = not identified)
  tab_prov_fe_body.tex       province-FE interaction (SEs/R2)
  tab_descriptive_body.tex   descriptive statistics (panel_scaling)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np
import pandas as pd

CORE = "results/tables/core"
OUT = "results/tex_tables"
os.makedirs(OUT, exist_ok=True)


def w(name: str, lines: list[str]):
    path = f"{OUT}/{name}"
    with open(path, "w") as f:
        f.write("% Generated by scripts/make_tex_tables.py — do not edit by hand\n")
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path}")


def tab_interaction():
    d = pd.read_csv(f"{CORE}/interaction_ols.csv").set_index("Sector")
    order = ["Secondary", "Tertiary", "NonAgri", "Primary"]
    rows = []
    for s in order:
        r = d.loc[s]
        ustar = f"{r['u_star']:.2f}" if r["beta1"] > 0.5 else "---"
        label = {"NonAgri": "Non-agricultural", "Secondary": "Secondary",
                 "Tertiary": "Tertiary", "Primary": "Primary"}[s]
        rows.append(
            f"{label} & ${r['beta0']:.2f}$\\;(${r['se_beta0']:.3f}$) & "
            f"${r['beta1']:.2f}$\\;(${r['se_beta1']:.3f}$) & {ustar} & "
            f"{r['R2']:.2f} & {int(r['N']):,} \\\\")
    w("tab_interaction_body.tex", [
        "\\begin{tabular}{lccccc}", "\\toprule",
        "Sector & $\\beta_0$ (SE) & $\\beta_1$ (SE) & $u^{*}$ & $R^2$ & $N$ \\\\",
        "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"])


def _ci(summary, spec, period, q, fmt="{:.3f}"):
    m = summary[(summary["saai_spec"] == spec) & (summary["period"] == period)
                & (summary["quantity"] == q)]
    if len(m) == 0:
        return None
    r = m.iloc[0]
    return (fmt + " [" + fmt + ", " + fmt + "]").format(
        r["boot_median"], r["ci_lo"], r["ci_hi"])


def tab_kramers():
    pts = pd.read_csv("results/tables/km_point_estimates.csv")
    boot = pd.read_csv("results/tables/km_bootstrap_ci.csv")
    mle = pd.read_csv("results/tables/mle_fits.csv").set_index("period")
    mdr = pd.read_parquet("results/tables/mle_bootstrap_draws.parquet")

    def km_pt(period, col):
        m = pts[(pts["saai_spec"] == "multi") & (pts["period"] == period)
                & (pts["binning"] == "equal_width")]
        return m.iloc[0][col]

    def mle_ci(period, q, fmt="{:.3f}"):
        # Point estimate from the full-sample fit with a county-block
        # bootstrap percentile interval, matching the binned-KM rows.
        v = mdr[f"{q}_{period}"].dropna()
        return (fmt + " [" + fmt + ", " + fmt + "]").format(
            mle.loc[period, q], v.quantile(.025), v.quantile(.975))

    rows = []
    for period, label in (("pre", "Pre (2000--2012)"),
                          ("during", "During (2013--2019)")):
        n = int(km_pt(period, "n_pairs"))
        rows.append(
            f"{label} & Binned KM & {n:,} & "
            f"${km_pt(period, 'new_delta_V'):.3f}$ "
            f"[${_num(boot, period, 'delta_V', 'ci_lo')}$, ${_num(boot, period, 'delta_V', 'ci_hi')}$] & "
            f"{km_pt(period, 'new_mean_diffusion'):.3f} & "
            f"{km_pt(period, 'new_gamma'):.2f} & "
            f"{km_pt(period, 'new_tau_mfpt'):.1f} "
            f"[{_num(boot, period, 'tau_mfpt', 'ci_lo', '{:.1f}')}, {_num(boot, period, 'tau_mfpt', 'ci_hi', '{:.1f}')}] \\\\")
        m = mle.loc[period]
        rows.append(
            f" & Parametric MLE & {n:,} & {mle_ci(period, 'delta_V')} & "
            f"{m['mean_diffusion']:.3f} & {m['gamma']:.2f} & "
            f"{mle_ci(period, 'tau_mfpt', '{:.1f}')} \\\\")
    rows.append("\\midrule")
    rows.append("Post (2020--2023) & --- & 91 & "
                "\\multicolumn{4}{c}{not identified (0 reliable bins; "
                "selective attrition, see text)} \\\\")
    w("tab_kramers_body.tex", [
        "\\begin{tabular}{llccccc}", "\\toprule",
        "Period & Estimator & $n$ pairs & $\\Delta V$ [95\\% CI] & "
        "$\\bar{D}$ & $\\Gamma$ & $\\tau_{\\mathrm{MFPT}}$ (yr) [95\\% CI] \\\\",
        "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"])


def _num(boot, period, q, col, fmt="{:.3f}"):
    m = boot[(boot["saai_spec"] == "multi") & (boot["period"] == period)
             & (boot["quantity"] == q)]
    return fmt.format(m.iloc[0][col])


def tab_prov_fe():
    d = pd.read_csv(f"{CORE}/interaction_prov_fe.csv").set_index("Sector")
